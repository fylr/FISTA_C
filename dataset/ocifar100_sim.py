"""OCIFAR100_sim dataset loader (simulated lensless dataset).

OCIFAR100_sim shares the *same* ground-truth directory as OCIFAR100.  The two
datasets differ only in the blur source:

    OCIFAR100     -> blur/      (real captured blur)   PSF: PhlatCam_psf.png
    OCIFAR100_sim -> blur_sim/  (simulated blur)       PSF: PhlatCam_psf_sim.png

Therefore both datasets live under one common root directory that contains
``gt/`` (shared), ``blur/`` (captured) and ``blur_sim/`` (simulated):

    ocifar100/                 # common root for OCIFAR100 AND OCIFAR100_sim
    ├── gt/                    # ground-truth scenes (SHARED by both datasets)
    │   ├── train/             # 50,000 images in 100 class folders
    │   └── test/              # 10,000 images in 100 class folders
    ├── blur/                  # real captured blur  (OCIFAR100)
    │   ├── train/
    │   └── test/
    └── blur_sim/              # simulated blur      (OCIFAR100_sim)
        ├── train/
        └── test/

The simulated blur images are generated by convolving the ground-truth scenes
with the measured PSF and adding Poisson + Gaussian noise (see Section 3.1 of
the paper).
"""

from pathlib import Path
from typing import Callable, Optional, Tuple, Union

import torch

from dataset.ocifar100 import OCIFAR100


class OCIFAR100Sim(OCIFAR100):
    """OCIFAR100_sim simulated dataset.

    Thin convenience wrapper around :class:`OCIFAR100` that loads the
    *simulated* blur (``blur_sim/``) while sharing the same ``gt/`` directory.
    Both datasets therefore read from the identical root directory.

    Args:
        root:           common ``ocifar100/`` directory (contains gt/, blur/,
                        blur_sim/).
        split:          ``'train'`` or ``'test'``.
        blur_size:      (H, W) center crop size for blur images.
        obj_size:       (H, W) center crop size for gt images.
        is_train:       if True, apply training augmentation.
        blur_transform: optional custom transform for blur.
        gt_transform:   optional custom transform for gt.
    """

    def __init__(self, root: Union[str, Path], split: str = "test",
                 blur_size: tuple = (112, 112), obj_size: tuple = (96, 96),
                 is_train: bool = False,
                 blur_transform: Optional[Callable] = None,
                 gt_transform: Optional[Callable] = None):
        # blur_type="blur_sim" selects the simulated blur; gt/ is shared.
        super().__init__(root, split=split, blur_type="blur_sim",
                         blur_size=blur_size, obj_size=obj_size,
                         is_train=is_train,
                         blur_transform=blur_transform, gt_transform=gt_transform)


def get_ocifar100sim_loaders(root: Union[str, Path],
                             blur_size: tuple = (112, 112),
                             obj_size: tuple = (96, 96),
                             batch_size: int = 16,
                             num_workers: int = 4,
                             train_ratio: float = 0.9,
                             seed: int = 0) -> Tuple[torch.utils.data.DataLoader,
                                                      torch.utils.data.DataLoader]:
    """Create train/validation DataLoaders for OCIFAR100_sim.

    Args:
        root:        common ``ocifar100/`` directory.
        blur_size:   blur center crop size.
        obj_size:    gt center crop size.
        batch_size:  batch size.
        num_workers: number of data loading workers.
        train_ratio: fraction of the train split used for training.
        seed:        random seed for the train/val split.

    Returns:
        (train_loader, val_loader)
    """
    from torch.utils.data import DataLoader, random_split

    full_train = OCIFAR100Sim(root, split="train", blur_size=blur_size,
                              obj_size=obj_size, is_train=True)
    test_set = OCIFAR100Sim(root, split="test", blur_size=blur_size,
                            obj_size=obj_size, is_train=False)

    if train_ratio < 1.0:
        n_train = int(len(full_train) * train_ratio)
        n_val = len(full_train) - n_train
        train_set, val_set = random_split(
            full_train, [n_train, n_val],
            generator=torch.Generator().manual_seed(seed),
        )
        # Validation set should not use training augmentation.
        val_set.dataset.is_train = False
        val_set.dataset.blur_transform = _make_eval_transform(blur_size)
        val_set.dataset.gt_transform = _make_eval_transform(obj_size)
    else:
        train_set = full_train
        val_set = test_set

    train_loader = DataLoader(train_set, batch_size=batch_size, shuffle=True,
                              num_workers=num_workers, pin_memory=True, drop_last=True)
    val_loader = DataLoader(val_set, batch_size=batch_size, shuffle=False,
                            num_workers=num_workers, pin_memory=True)
    return train_loader, val_loader


def _make_eval_transform(size):
    """Build an eval (no augmentation) transform of the given crop size."""
    from dataset.base import make_transforms
    return make_transforms(size, is_train=False)
